// 把所有新闻展平成一个数组（最新的在最前面）
function flattenNews() {
    const allNews = [];
    // 按日期从新到旧排序
    const dates = Object.keys(newsByDate).sort((a, b) => new Date(b) - new Date(a));
    
    dates.forEach(date => {
        newsByDate[date].forEach(news => {
            allNews.push({
                ...news,
                time: date.slice(5) + " " + news.time
            });
        });
    });
    
    return allNews;
}

